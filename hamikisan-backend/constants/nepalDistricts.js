const districtId = (district) =>
  `district_${district.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '')}`;

const districtById = new Map(districts.map((district) => [districtId(district), district]));
const normalizeDistrict = (value) => {
  if (typeof value !== 'string') return null;
  const normalized = value.trim().toLowerCase();
  if (normalized === 'nawalpur') return 'Nawalparasi East';
  if (normalized === 'parasi') return 'Nawalparasi West';
  const match = districts.find((district) => district.toLowerCase() === normalized);
  return match || null;
};

module.exports = { districts, districtId, districtById, normalizeDistrict };
